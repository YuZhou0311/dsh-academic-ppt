const byId=new Map(REFERENCE_TEMPLATES.map(t=>[t.id,t]));
export function getReferenceTemplate(id){return byId.get(id);}

// Development invariant: malformed catalog edits cannot silently become runtime geometry.
if(REFERENCE_TEMPLATES.length!==48 || byId.size!==48)throw new Error('Reference catalog must contain 48 unique templates.');
for(const t of REFERENCE_TEMPLATES){
  if(!REFERENCE_CATEGORIES.some(c=>c.id===t.category))throw new Error('Unknown reference category: '+t.id);
  for(const [role,value] of Object.entries(t.slots))for(const box of Array.isArray(value)?value:[value]){
    if(!box || !['x','y','w','h'].every(k=>Number.isFinite(box[k])) || box.x<0 || box.y<0 || box.w<=0 || box.h<=0 || box.x+box.w>1280 || box.y+box.h>720)throw new Error('Invalid reference geometry: '+t.id+'/'+role);
  }
  if(t.prompts.length!==t.slots.cards.length)throw new Error('Every text region needs a content role: '+t.id);
}

function T(id,name,layout,description,slots,prompts,extra={}){
  const cards=slots.cards||[],figures=slots.figures||[],nodes=slots.nodeBoxes||[];
  return {id,category:id.split('-')[0],name,layout,description,
    slots:{cards,figures,...slots},
    requirements:{cards:{min:cards.length,max:cards.length},figures:{min:figures.length,max:figures.length},nodes:{min:nodes.length,max:nodes.length},chart:!!slots.chart,table:!!slots.table},
    cardStyles:cards.map((box,i)=>box.h<115?'compact':STYLES[id]?.[i]||'plain'),prompts,
    suggestedSeconds:60,...extra};
}
